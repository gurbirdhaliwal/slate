"""The context layer: which docs exist, where they live, what they watch.

Slate maintains a fixed, small doc set (product doc §7) — a routing file at
the repo root plus focused docs under ``.slate/``. Each doc is either
*generated* (Slate owns a marked auto-block inside it and can rewrite it
from a scan) or *human-owned* (Slate only tracks its freshness metadata).

Human edits outside the auto-block always survive a sync.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from . import frontmatter, gitutil, globs
from .frontmatter import Meta
from .scanner import RepoScan

SLATE_DIR = ".slate"
AUTO_BEGIN = "<!-- slate:auto — generated by `slate sync`; edit outside this block -->"
AUTO_END = "<!-- /slate:auto -->"

# Statuses a doc can be in (see freshness.py for how they're derived).
FRESH = "fresh"
STALE = "stale"
NEEDS_VERIFICATION = "needs-verification"


@dataclass(frozen=True)
class DocSpec:
    name: str          # short name used on the CLI: `slate sync modules`
    rel_path: str      # repo-relative path of the Markdown file
    title: str
    generated: bool    # True → has an auto-block Slate rewrites on sync
    read_order: int    # position in the "first read" path (0 = skip)
    # True → entries are only ever added, never rewritten. Lets the merge
    # driver union two branches' entries instead of conflicting on the
    # append point; see merge.py.
    append_only: bool = False

    def path(self, root: Path) -> Path:
        return root / self.rel_path


DOC_SPECS: list[DocSpec] = [
    DocSpec("agents", "AGENTS.md", "Agent routing", True, 1),
    DocSpec("read-next", f"{SLATE_DIR}/read-next.md", "Read next — current focus", False, 2),
    DocSpec("architecture", f"{SLATE_DIR}/architecture.md", "Architecture", True, 3),
    DocSpec("modules", f"{SLATE_DIR}/modules.md", "Module map", True, 4),
    DocSpec("workflows", f"{SLATE_DIR}/workflows.md", "Workflows", True, 5),
    DocSpec("decisions", f"{SLATE_DIR}/decisions.md", "Decision log", False, 6, append_only=True),
]


# Claude Code reads this file, not AGENTS.md, so Slate writes it as a one-line
# import of the layer (see agentcfg.bridge_claude). It makes no claims about
# the code, so it is a context-layer path rather than a tracked doc.
CLAUDE_BRIDGE = "CLAUDE.md"

# Docs never invalidate docs: these paths are excluded from change detection
# and from the watched-content digest alike. The Claude bridge is in here for
# the same reason — on a repo with no source directories the module map
# watches `**`, and a doc going stale because Slate wrote its own pointer file
# would be pure noise.
CONTEXT_DOC_PATHS = {spec.rel_path for spec in DOC_SPECS} | {CLAUDE_BRIDGE}


def spec_by_name(name: str) -> DocSpec | None:
    for spec in DOC_SPECS:
        if spec.name == name or spec.rel_path == name:
            return spec
    return None


def default_watches(spec: DocSpec, scan: RepoScan) -> list[str]:
    """The code paths whose changes can invalidate this doc."""
    src = [f"{d}/**" for d in scan.source_dirs]
    build_files = [
        "Makefile", "package.json", "pyproject.toml", "pom.xml",
        "docker-compose*", "Dockerfile*", ".github/workflows/**",
    ]
    if spec.name == "agents":
        return [f"{SLATE_DIR}/**"]
    if spec.name == "architecture":
        return src + ["pyproject.toml", "package.json", "pom.xml"]
    if spec.name == "modules":
        return src or ["**"]
    if spec.name == "workflows":
        return build_files
    # read-next names live symbols in prose (`freshness.evaluate_all`,
    # `slate/merge.py`, ...), so it earns a watch-based verdict like the
    # generated docs. Left unwatched it returned FRESH before its body was
    # ever read, which kept every claim in the layer's most-read doc unchecked
    # for the whole of this project's history.
    if spec.name == "read-next":
        return src or ["**"]
    # decisions stays attestation-based: it is an append-only record, and a
    # past decision remains true as a statement about the past.
    return []


@dataclass
class ContextDoc:
    spec: DocSpec
    meta: Meta
    body: str
    # 1-based line in the *file* where `body` starts, so a claim's line number
    # (which the segmenter reports against the body) can be blamed on disk.
    body_line: int = 1

    @property
    def watches(self) -> list[str]:
        value = self.meta.get("slate_watches", [])
        return value if isinstance(value, list) else [str(value)]

    @property
    def synced_commit(self) -> str | None:
        value = self.meta.get("slate_synced_commit")
        return str(value) if value else None


def load(root: Path, spec: DocSpec) -> ContextDoc | None:
    path = spec.path(root)
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    meta, body = frontmatter.parse(text)
    # `body` is always a suffix of `text`, so the prefix length gives the offset.
    return ContextDoc(spec, meta, body, text.count("\n", 0, len(text) - len(body)) + 1)


def load_all(root: Path) -> list[ContextDoc]:
    return [doc for spec in DOC_SPECS if (doc := load(root, spec))]


def save(root: Path, doc: ContextDoc) -> None:
    path = doc.spec.path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(frontmatter.render(doc.meta, doc.body), encoding="utf-8")


def stamp(root: Path, doc: ContextDoc, commit: str | None) -> None:
    """Record that this doc reflects the repo as of ``commit``.

    Alongside the commit anchor, a content digest of the watched file set is
    recorded: history rewrites (rebase/squash-merge) kill commit anchors, and
    the digest lets the freshness engine prove "nothing watched changed since
    the last sync" even when the anchor is gone.
    """
    doc.meta["slate_doc"] = doc.spec.name
    doc.meta["slate_generated"] = doc.spec.generated
    if commit:
        doc.meta["slate_synced_commit"] = commit
    doc.meta["slate_synced_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    doc.meta["slate_synced_digest"] = watched_digest(root, doc.watches)
    if "slate_watches" in doc.meta:  # keep the watch list last in the frontmatter
        doc.meta["slate_watches"] = doc.meta.pop("slate_watches")


def watched_digest(root: Path, watches: list[str]) -> str:
    """Deterministic fingerprint of the watched files' current content.

    sha256 over sorted (path, content-hash) pairs of every working-tree file
    matching the watch globs, context docs excluded. Same watched content →
    same digest, regardless of what happened to the commit graph.
    """
    h = hashlib.sha256()
    if watches:
        matched = sorted(
            p for p in gitutil.list_files(root)
            if p not in CONTEXT_DOC_PATHS and globs.any_match(watches, p)
        )
        for path in matched:
            h.update(path.encode("utf-8", "replace") + b"\0")
            try:
                h.update(hashlib.sha256((root / path).read_bytes()).digest())
            except OSError:
                h.update(b"unreadable")
            h.update(b"\n")
    return h.hexdigest()[:16]


def get_auto_block(body: str) -> str | None:
    """The current content between the auto markers, or None if absent."""
    begin = body.find(AUTO_BEGIN)
    end = body.find(AUTO_END)
    if begin == -1 or end == -1 or end < begin:
        return None
    return body[begin + len(AUTO_BEGIN):end].strip()


def replace_auto_block(body: str, generated: str) -> str:
    """Swap the content between the auto markers, preserving everything else.

    If the markers are missing (a human deleted them), the generated block is
    appended rather than clobbering the human text.
    """
    block = f"{AUTO_BEGIN}\n{generated.strip()}\n{AUTO_END}"
    begin = body.find(AUTO_BEGIN)
    end = body.find(AUTO_END)
    if begin == -1 or end == -1 or end < begin:
        return body.rstrip() + "\n\n" + block + "\n"
    return body[:begin] + block + body[end + len(AUTO_END):]
